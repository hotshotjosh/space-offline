#!/usr/bin/env python3
"""Write server/THIRD-PARTY.txt: licence notices for every allowlisted crate.

Run in the build image, where the registry is (the output goes to stdout, so
the container needs no write access):

    tools/dev.sh python3 -I /repo/tools/dep-notices.py --registry /usr/share/cargo/registry \\
        > server/THIRD-PARTY.txt

For each row of server/deps.allow: name, version, licence, then the crate's
LICENSE*, COPYING* and NOTICE* files verbatim. `tools/check_deps.py
--registry` fails when the committed file differs from this output.

Standard library only.
"""
import sys as _sys

if __name__ == "__main__":
    _sys.path.append(_sys.path.pop(0))

import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
RULE = "=" * 72


def _check_deps():
    spec = importlib.util.spec_from_file_location("check_deps", HERE / "check_deps.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def notice_files(crate_dir):
    """The top-level licence and notice files of a crate directory, sorted."""
    if not pathlib.Path(crate_dir).is_dir():
        return []
    return sorted(p for p in pathlib.Path(crate_dir).iterdir()
                  if p.is_file() and p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")))


def render(rows, registry):
    """The THIRD-PARTY.txt text for `rows` (dicts with name, version, licence) from `registry`."""
    out = ["Third-party crates compiled into the server and their licences.\n"
           "Generated by tools/dep-notices.py from the build image's crate registry;\n"
           "do not edit. The crate list is server/deps.allow.\n"]
    for r in sorted(rows, key=lambda r: (r["name"], r["version"])):
        d = pathlib.Path(registry) / f"{r['name']}-{r['version']}"
        out.append(f"{RULE}\n{r['name']} {r['version']}\nLicence: {r['licence']}\n{RULE}\n")
        for f in notice_files(d):
            body = f.read_text(errors="replace").rstrip("\n")
            out.append(f"--- {f.name} ---\n{body}\n")
    return "\n".join(out)


def main(argv):
    if len(argv) != 2 or argv[0] != "--registry":
        print("usage: dep-notices.py --registry DIR", file=sys.stderr)
        return 2
    cd = _check_deps()
    rows, problems = cd.parse_allow((cd.SERVER / "deps.allow").read_text())
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    sys.stdout.write(render(rows, argv[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
